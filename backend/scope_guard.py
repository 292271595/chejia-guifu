"""领域守卫：判断一个问题是不是「跟车、驾无关」。

为什么需要这一层
────────────────
知识库只收 24 部道路交通相关法规。问「护照怎么办」这类问题时，检索层
必然召回一堆不相干的片段（向量检索永远会返回 top-k，不管相不相关），
生成层再拿这些片段组织出一段看着挺像回事的答案——既烧 token 又误导人，
比老老实实说「这不归我管」差得多。

判定策略：宁可放过，不可误杀
────────────────────────────
误杀一个正常的车驾问题，用户会觉得「这也不懂」，信任直接掉；漏答一个
护照问题，只是多花一次检索。两者代价不对等，所以判定做成**双重条件**：

    命中明确的其它领域词  且  通篇没有任何车驾痕迹   →  才拒答

只要出现一个「车」「驾」「扣」「违章」这类线索就放行，哪怕它同时提到
护照（「办驾照要护照吗」这种问法必须答）。

三类问题因此不会被误判：
  · 中性句（「那要多久」「可以吗」——残句，交给追问补全，不在这里拦）
  · 跨域句（「用护照能办驾驶证吗」——有车驾线索，放行）
  · 长描述（超过 MAX_LEN 字的多半在叙述经过，词杂，不判）

为什么不干脆用检索分数兜底
────────────────────────
分数阈值在不同问法上波动很大，实测正常问题的 top1 分数能低到 0.4 以下
（问得口语就会这样），而无关问题的分数偶尔也能上 0.5。拿它当判据会
误杀正常问题，而且每次都要真跑一遍检索，正好抵消了「省资源」的目的。
这里全部靠词表，纯字符串匹配，微秒级。
"""
