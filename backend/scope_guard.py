# ── 假朋友：含车驾的字，但语义已经在别的领域 ──
# 「火车票改签规则」里的「车」不是机动车，「车票」也不是车牌。
# 不剥掉这几类，它们会白白把超纲问题放行。
_FALSE_FRIEND = ("火车票", "高铁票", "动车票", "汽车票", "车票", "火车", "动车")

# ── 弱词：在车驾和他域里都成立，不能单独作为「这是车驾问题」的证据 ──
# 「房产过户」「公积金提取」同样叫「过户」「提取」，跟车辆过户不是一回事。
# 判据：如果一个问题的车驾线索**全靠弱词撑着**，同时命中了明确的他域词，
# 就以他域为准。只要还有「车」「驾」这类强线索，就仍然放行。
#   「房产过户流程」      → 剥掉「过户」后什么都没有 → 判他域
#   「公司名下的车过户给个人」→ 剥完还剩「车」          → 放行
_WEAK_AUTO = ("过户", "保险", "登记", "发票", "检验", "审验", "申领", "补办", "办理")


def _strip_false_friends(text: str) -> str:
    for w in _FALSE_FRIEND:
        text = text.replace(w, "")
    return text


def enabled() -> bool:
    """开关：SCOPE_GUARD=off 关掉。

    留这个开关是为了评测——跑题库回归时要确认「拒答层没有吃掉任何一题」，
    关掉才能对比出差异；线上出问题时也能立刻降级回原来的行为。
    """
    v = (os.getenv("SCOPE_GUARD", "on") or "on").strip().lower()
    return v not in ("off", "0", "false", "no")


def _has_auto_cue(text: str) -> bool:
    """有没有车驾痕迹。有任何一点就算有。"""
    if any(ch in text for ch in _AUTO_CHARS):
        return True
    if any(w in text for w in _AUTO_WORDS):
        return True
    for m in _CODE_RE.finditer(text):
        if m.group(0) in _CODE_ALLOW:
            return True
    return False


def _domain_of(text: str) -> Optional[str]:
    for domain, words in _OFF_TOPIC.items():
        for w in words:
            if w in text:
                return domain
    return None


def check(question: str) -> Optional[str]:
    """返回命中的他域名称；返回 None 表示「不拦」。

    注意 None 的含义是「不确定，交给后面流程」，不是「确定是车驾问题」。
    中性残句、长描述、以及所有拿不准的情况都返回 None。
    """
    t = (question or "").strip()
    if not t or len(t) > MAX_LEN:
        return None

    domain = _domain_of(t)
    core = _strip_false_friends(t)

    if not _has_auto_cue(core):
        # 完全没有车驾痕迹：命中他域就拒，没命中（「那要多久」这类残句）放行
        return domain
    if not domain:
        return None

    # 有车驾痕迹，同时命中了明确的他域词。把弱词剥掉再看一次：
    # 剥完还有线索说明这是真的车驾问题（「公司名下的车过户给个人」），放行。
    weak = core
    for w in _WEAK_AUTO:
        weak = weak.replace(w, "")
    if not _has_auto_cue(weak):
        return domain
    return None


def refusal_text(question: str, domain: str) -> str:
    """拒答话术。

    三条要求：说清楚范围、说清楚为什么这次不答、给出一个可走的路。
    不编造任何热线号码——号码写错了比不写更糟，用户打过去是空号。
    """
    q = (question or "").strip()
    shown = q if len(q) <= 24 else q[:24] + "…"
    return (
        f"**这个问题不在我的范围内。**\n\n"
        f"我只管车辆和驾驶证的事：申领、增驾、记分、年检、换证、过户、"
        f"事故处理、违法处罚这些，依据的是 24 部道路交通法规原文。\n\n"
        f"「{shown}」属于{domain}方面的业务，我这儿没有对应的法规，"
        f"硬答只能给你编一段看着像的——那比不答更耽误事，所以我停在这里。\n\n"
        f"这件事建议走对应的政务服务平台，或者直接问当地办理窗口。\n"
        f"如果是跟车有关的事，换个说法再问我就行。"
    )
