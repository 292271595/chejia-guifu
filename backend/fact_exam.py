def norm_subject(s: str) -> str:
    """把科目写法归一到法规正式名：科目4→安全文明，科目1/2/3→中文数字。

    为什么要连"科目2"这种阿拉伯写法一起归一：处理器内部到处是
    `re.search(r"科目二", q)` 这样的判定，问句写"科目2多久能约考"时一条都不命中，
    整句掉到检索层。阿拉伯写法在手机输入里非常常见，不能当错别字忽略。
    """
    s = s.replace("科目四", "安全文明").replace("科目4", "安全文明")
    s = s.replace("科四", "安全文明")
    s = s.replace("科目1", "科目一").replace("科目2", "科目二").replace("科目3", "科目三")
    # 线上错答（2026-11-19）：用户问「科一没过能补考吗」，整句掉检索层，答成
    # 「在规定的时间内重新预约补考」，把「当场补考一次」漏掉，条号还引成第四十条。
    # 事实层本来就有正确答案 EXAM:TIMES_K1（第四十七条、当场补考一次），
    # 但此前只归一「科目1/科四」，「科一」从没换成「科目一」，各分支的
    # `科目一` 判定一律摸不着它。科二、科三同理：实测 25 条简称问法里 21 条漏答，
    # 包括「科二怎么约考」「科二多少分」「科三没过能补考吗」。
    # 手机口语几乎都写简称，必须在这里一次性归一，不能让每个分支各补一遍。
    for short, full in (("科一", "科目一"), ("科二", "科目二"), ("科三", "科目三"),
                        ("科1", "科目一"), ("科2", "科目二"), ("科3", "科目三")):
        s = s.replace(short, full)
    return s

