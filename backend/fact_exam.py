def _subj2_items(code: Optional[str]) -> Tuple[str, str]:
    if code in AB_CODES:
        return "AB", SUBJECT2_ITEMS["AB"]
    if code in ("C2", "C5"):
        return "C2", SUBJECT2_ITEMS["C2"]
    if code == "C6":
        return "C6", SUBJECT2_ITEMS["C6"]
    if code in ("D", "E", "F"):
        return "MOTO", SUBJECT2_ITEMS["MOTO"]
    return "C1", SUBJECT2_ITEMS["C1"]


def add_exam_plan(holder: Optional[str], target: Optional[str]) -> Optional[Tuple[str, str, str]]:
    """返回 (考试科目串, 条款, 说明)。None 表示不适用（非增驾场景）。"""
    if not target:
        return None
    if holder and holder == target:
        return None

    # C2 → C1
    if holder == "C2" and target == "C1":
        return ("科目二 + 科目三（含科目三道路驾驶技能和安全文明驾驶常识）",
                "第三十条第二款",
                "C2 增驾 C1 不需要考科目一。")

    # 增驾 C6（第三十条第三款列举 A1/A3/B1/B2/C1/C2；
    # 持 A2 本来已准驾 C6，若另行考取按同一口径说明，避免答成"考三科"）
    if target == "C6" and holder in ("A1", "A3", "B1", "B2", "C1", "C2", "A2"):
        return ("科目二 + 科目三安全文明驾驶常识",
                "第三十条第三款",
                "增驾 C6 **不考科目一，也不考科目三道路驾驶技能**，只考科目二和科目三安全文明驾驶常识。")

    # 摩托车内部增驾
    if holder == "F" and target in ("D", "E"):
        return ("科目二 + 科目三", "第三十条第四款", "持 F 增驾 D/E 不需要考科目一。")
    if holder == "E" and target == "D":
        return ("科目二 + 科目三", "第三十条第四款", "持 E 增驾 D 不需要考科目一。")

    # 其他增驾：按初次申领科目执行
    return ("科目一 + 科目二 + 科目三", "第三十条第一款",
            "除法规单列的三种情形（C2→C1、增驾C6、摩托车内部增驾）外，"
            "其他增驾仍按初次申领的考试科目执行，三科都要考。")


