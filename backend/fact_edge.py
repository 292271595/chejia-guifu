# ── 3. 实习期扣 6 分会延长实习期吗 ────────────────────────────────
def q_intern_six_points(q: str) -> Optional[Dict]:
    if not re.search(r"实习", q):
        return None
    m = re.search(r"(?:扣|记|扣了|记了)\s*(?:了|到|够)?\s*(\d{1,2}|[一二三四五六七八九十]+)\s*分", q)
    if not m:
        return None
    raw = m.group(1)
    cn = {"一": 1, "二": 2, "三": 3, "四": 4, "五": 5, "六": 6,
          "七": 7, "八": 8, "九": 9, "十": 10}
    n = int(raw) if raw.isdigit() else cn.get(raw)
    if n is None or n >= 12 or n < 1:
        return None
    if re.search(r"(满分学习|怎么学|学几天|考科目一|清分)", q):
        return None
    return result(
        f"**不会延长。现行 172 号令里没有「实习期扣 {n} 分延长实习期」这项处理**，"
        "实习期仍是初次取得该类准驾车型后的 12 个月。\n\n"
        f"{LAW_LIC}第八十条对实习期记分只规定了一条后果："
        "**实习期内发生的道路交通安全违法行为被记满 12 分的，注销其实习的准驾车型驾驶资格。**"
        f" 扣 {n} 分、没满 12 分，不触发注销，也不延长实习期。\n\n"
        "**但要留意两件相邻的事，别混进来：**\n"
        "· 一旦攒到 12 分就不是「学习完就没事」了——直接注销实习的准驾车型，得重新考；\n"
        "· 持 A1/A2/A3/B1/B2 这类大中型客货车驾驶证的，**每个记分周期结束后 30 日内要审验**，"
        "只有本周期零记分才免予审验（第七十二条第三款）。这是审验义务，不是实习期延长。\n\n"
        "⚠️ 网上还在流传「实习期记 6 分以上延长一年、再记 6 分注销」的说法，"
        "这句在项目知识库收录的现行法规原文里查不到；现行条文对实习期记分"
        "只写了「记满 12 分注销」这一条，所以这里按现行条文答，不给延长天数。",
        [source(f"{LAW_LIC}第八十条",
                "机动车驾驶人在实习期内发生的道路交通安全违法行为被记满12分的，"
                "注销其实习的准驾车型驾驶资格。", SRC_LIC),
         source(f"{LAW_LIC}第七十六条、第七十二条",
                "机动车驾驶人初次取得汽车类准驾车型或者初次取得摩托车类准驾车型后的12个月为实习期；"
                "持有大型客车、重型牵引挂车、城市公交车、中型客车、大型货车驾驶证的驾驶人，"
                "应当在每个记分周期结束后30日内接受审验，但一个记分周期内没有记分记录的，"
                "免予本记分周期审验。", SRC_LIC)],
        "EDGE:INTERN_SIX_POINTS")


