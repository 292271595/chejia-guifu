# 压测发现："交通事故责任是怎么认定的"走 RAG 时生成 12 秒超时降级，
# 用户看到的是原文堆砌。这题答案由实施条例第九十一条锁死（四档划分），
# 属于确定性内容，且是高频入口问题，适合直答。
_RESP_PRINCIPLE = re.compile(r"(责任.{0,6}(怎么|如何|怎样)?(认定|划分|划分标准|怎么分|怎么划)|"
                             r"(认定|划分).{0,4}责任|责任(比例|大小).{0,6}(怎么|如何))")


def q_liability_principle(question: str) -> Optional[Dict]:
    """交通事故责任认定的依据与四档划分。"""
    if not _RESP_PRINCIPLE.search(question):
        return None
    # 涉及死亡/伤情的具体刑事责任问题，交给 q_accident_death
    if re.search(r"(死亡|致死|撞死|身亡|判几|坐牢|量刑|构成犯罪)", question):
        return None

    lines = [
        "**核心一句话：看两个东西——你的行为对事故起了多大作用，你的过错有多严重。**",
        "",
        "《道路交通安全法实施条例》第九十一条定的就是这个标准："
        "公安机关交通管理部门应当根据**当事人的行为对发生道路交通事故所起的作用**"
        "以及**过错的严重程度**，确定当事人的责任。",
        "",
        "**四档划分（第九十一条 + 道交法第七十三条）**",
        "· **全部责任**：因一方当事人的过错导致事故的，该方承担全部责任；",
        "· **主要 / 同等 / 次要责任**：两方或两方以上都有过错的，"
        "按各自行为对事故发生的作用和过错严重程度，分别承担主要、同等、次要责任；",
        "· **无责任**：各方均无导致事故的过错，属交通意外事故的，各方均无责任；",
        "· **他方无责任**：一方当事人**故意**造成事故的，他方无责任。",
        "",
        "**谁来做、什么时候出**",
        "由公安机关交通管理部门根据**现场勘验、检查、调查情况**和有关的**检验、鉴定结论**，"
        "及时制作**道路交通事故认定书**（道交法第七十三条）。认定书是处理赔偿的重要证据，"
        "但它不是行政处罚决定，对认定不服可以申请**复核**。",
        "",
        "**几个实务要点**",
        "· **逃逸**导致事故责任无法认定的，**推定逃逸方负全部责任**；",
        "· **故意破坏、伪造现场、毁灭证据**的，同样承担全部责任；",
        "· 一方**有条件报案而未报案**或者未及时报案，导致责任无法认定的，也要承担相应责任；",
        "· 责任比例直接影响民事赔偿的分担，也影响是否构成交通肇事罪（刑事上要求"
        "「全部或主要责任」死亡一人，或「同等责任」死亡三人以上）。",
    ]
    return result(
        "\n".join(lines),
        [source("《中华人民共和国道路交通安全法实施条例》第九十一条；《道路交通安全法》第七十三条",
                "公安机关交通管理部门应当根据当事人的行为对发生道路交通事故所起的作用以及过错的严重程度，"
                "确定当事人的责任。（一）因一方当事人的过错导致道路交通事故的，承担全部责任；"
                "（二）因两方或者两方以上当事人的过错发生道路交通事故的，根据其行为对事故发生的作用以及"
                "过错的严重程度，分别承担主要责任、同等责任和次要责任；（三）各方均无导致道路交通事故的过错，"
                "属于交通意外事故的，各方均无责任。一方当事人故意造成道路交通事故的，他方无责任",
                "road_traffic_safety_regulation.md")],
        "ACCIDENT:LIABILITY",
        aspects={"QUALIFY", "PROCEDURE"},
    )
