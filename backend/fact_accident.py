# 交强险在"驾驶人无资格/醉酒"情形下的赔付规则
# ============================================================
# 压测发现的问题：问"醉驾出事故交强险赔吗"，被醉驾罚则模板接走，答成
# "吊销驾驶证 + 追究刑事责任，5 年内不得重新取得"——处罚说得很对，
# 但用户问的是保险赔不赔，等于没答。
# 这类问题的答案由《交强险条例》第二十二条锁死，属确定性查表，不该交给模型。
_INS_TOPIC = re.compile(r"(交强险|强制保险|商业险|三者险|保险|理赔|赔付|赔不赔|能赔|垫付|追偿)")
_INS_TRIGGER = re.compile(r"(醉酒|醉驾|饮酒|酒驾|无证|未取得驾驶资格|逃逸|吸毒|毒驾|故意)")
_INS_QUESTION = re.compile(r"(赔|保险|理赔|垫付|追偿|限额)")


def q_insurance_drunk(question: str) -> Optional[Dict]:
    """无资格/醉酒驾驶情形下交强险是否赔付。"""
    if not _INS_TOPIC.search(question):
        return None
    if not _INS_TRIGGER.search(question):
        return None
    if not _INS_QUESTION.search(question):
        return None

    lines = [
        "**交强险要赔，但只垫付抢救费用，而且事后要向致害人追回——财产损失不赔。**",
        "",
        "《机动车交通事故责任强制保险条例》第二十二条把口径写死了：驾驶人**未取得驾驶资格"
        "或者醉酒**的、被保险机动车**被盗抢期间**肇事的、被保险人**故意**制造交通事故的，"
        "保险公司的责任是：",
        "",
        "· 在**医疗费用赔偿限额**内**垫付抢救费用**；",
        "· 垫付后**有权向致害人追偿**——这笔钱最终由醉驾者自己承担，不是保险公司兜底；",
        "· **财产损失不承担赔偿责任**（对方车辆维修费等，交强险一分不赔）。",
        "",
        "**别混淆三件事**：",
        "1. **受害人能拿到钱**——抢救费先由保险公司垫付，这是交强险的保障功能，伤者不用等肇事者掏钱；",
        "2. **致害人最终要还**——保险公司垫付后会追偿，等于自己承担；",
        "3. **商业三者险基本不赔**——醉酒驾驶属免责条款，商业险通常拒赔，需看具体条款约定。",
        "",
        "**超出交强险的部分**（死亡伤残金、后续治疗费等）由致害人自行承担；"
        "构成犯罪的，还要承担刑事责任（《刑法》第一百三十三条之一危险驾驶罪）。",
        "⚠️ 各地法院对\"垫付范围是否含死亡伤残限额\"存在裁判差异，实际理赔以保险公司核定和当地判例为准。",
    ]
    return result(
        "\n".join(lines),
        [source("《机动车交通事故责任强制保险条例》第二十二条",
                "有下列情形之一的，保险公司在机动车交通事故责任强制保险责任限额范围内垫付抢救费用，"
                "并有权向致害人追偿：（一）驾驶人未取得驾驶资格或者醉酒的；（二）被保险机动车被盗抢期间肇事的；"
                "（三）被保险人故意制造道路交通事故的。有前款所列情形之一，发生道路交通事故的，"
                "造成受害人的财产损失，保险公司不承担赔偿责任。",
                "compulsory_insurance_regulation.md")],
        "INS:DRUNK",
        aspects={"PENALTY"},
    )


# ============================================================
# 交强险限额与赔付顺序（固定数值，查表直答）
# ============================================================
# 压测发现：问"交强险无责赔付限额是多少"，模型诚实回答"知识库未明确列出，
# 请咨询保险公司"——这个行为是对的（没编数字），但用户什么都没得到。
# 根因是知识库只收了条例第二十三条的定性表述，没有限额数字。
# 已补 data/knowledge_base/compulsory_insurance_limits.md；
# 同时把这张固定数值表做成直答，不必每次让模型从条文里找。
_INS_Q = re.compile(r"(交强险|强制保险|三者险|商业险|保险)")
