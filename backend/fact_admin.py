# ============================================================
# 一、妨碍安全驾驶的疾病（第十五条第一项）
# ============================================================
def q_disease(q: str) -> Optional[Dict]:
    hits = [(k, v) for k, v in DISEASES if k in q]
    if not hits:
        return None
    names = "、".join(sorted({v for _, v in hits}))
    return result(
        f"**不能申请机动车驾驶证。**\n\n"
        f"依据第十五条第一项：有{names}等**妨碍安全驾驶疾病**的，不得申请机动车驾驶证。"
        "这项限制**不区分准驾车型**，对 A1 至 P 全部车型一律适用，也没有\"轻微就放行\"的例外。\n\n"
        "⚠️ 三个要点：\n"
        "1. 已持证后被查出上述疾病的，车辆管理所应当注销驾驶证（第七十九条第五项）；\n"
        "2. 申请校车驾驶资格的，还要求无癫痫病、精神病等病史（第八十七条第六项）；\n"
        "3. 是否属于上述疾病、当前是否已治愈，以医疗机构诊断和体检结论为准。",
        [source(f"{LAW}第十五条第一项",
                "有器质性心脏病、癫痫病、美尼尔氏症、眩晕症、癔病、震颤麻痹、精神病、痴呆以及"
                "影响肢体活动的神经系统疾病等妨碍安全驾驶疾病的，不得申请机动车驾驶证")],
        "DISEASE")


