# 十、逾期未审验 / 状态不符仍驾驶的罚则（第九十八、九十九条）
# ------------------------------------------------------------
# 这一类问题的共同点：用户问的不是"怎么办业务"，而是"我已经违规上路了，罚多少"。
# 单独建处理器，避免被"审验怎么办"的流程模板吞掉。
# ============================================================
def q_overdue_review(q: str) -> Optional[Dict]:
    if "审验" not in q:
        return None
    if not re.search(r"(逾期|未|没|不|超期).{0,6}审验|审验.{0,6}(逾期|过期|超期)", q):
        return None
    if not re.search(r"(开车|驾驶|上路|处罚|怎么罚|罚款|后果|扣分|记分)", q):
        return None

    return result(
        "**逾期不参加审验仍驾驶机动车的，处 200 元以上 500 元以下罚款（第九十九条第一款第三项），"
        "该项不记分。**\n\n"
        "依据：《机动车驾驶证申领和使用规定》第九十九条第一款：机动车驾驶人有下列行为之一的，"
        "由公安机关交通管理部门处 200 元以上 500 元以下罚款——\n"
        "（一）机动车驾驶证被依法扣押、扣留或者暂扣期间，采用隐瞒、欺骗手段补领机动车驾驶证的；\n"
        "（二）机动车驾驶人身体条件发生变化不适合驾驶机动车，仍驾驶机动车的；\n"
        "（三）**逾期不参加审验仍驾驶机动车的**。\n\n"
        "⚠️ 三点容易混淆的地方：\n"
        "- **逾期未审验 ≠ 逾期未换证**：未换证超过 1 年被注销，上路按「无证驾驶」处理（罚款并可拘留）；"
        "未审验只是罚 200—500 元，驾驶证本身仍有效；\n"
        "- 逾期未审验期间**不能办理换证、补证、增驾、转入**等业务，需先补审验；\n"
        "- 逾期未审验仍驾驶被查获后，仍应尽快到车管所补办审验，否则发生事故时保险公司可能据此主张免责。",
        [source(f"{LAW}第九十九条第一款第三项",
                "机动车驾驶人有下列行为之一的，由公安机关交通管理部门处200元以上500元以下罚款："
                "（三）逾期不参加审验仍驾驶机动车的")],
        "REVIEW:OVERDUE")
