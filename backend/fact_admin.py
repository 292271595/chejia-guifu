# 三、审验（第七十二条、第七十三条、第九十条）
# ============================================================
def q_review(q: str) -> Optional[Dict]:
    if not re.search(r"审验", q):
        return None

    # 清单型问句：问"哪些人要审验"，问的是适用对象，不是学时。
    # 原先 (学习|教育) 当学时信号用得太宽——"哪些驾驶人需要参加审验教育"里的
    # "教育"两个字被当成"问学多久"，于是一道清单题被答成"不少于 3 小时"。
    # 同一类错法：模板靠单个业务词命中，却不看用户问的是"谁"还是"多久"。
    if re.search(r"(哪些|什么人|哪些人|哪几类|几种|几类|谁需要|需要参加|要参加|哪些情形|什么情形)", q) \
            and not re.search(r"(多久|几小时|多长时间|多少小时|学时)", q):
        return result(
            "**需要参加审验的是 4 类人，都在记分周期结束后 30 日内办理：**\n\n"
            "1. **A、B 类驾驶人**（A1 大型客车、A2 重型牵引挂车、A3 城市公交车、B1 中型客车、"
            "B2 大型货车）——本记分周期**有记分**就要审；**一分没记的，免予本记分周期审验**"
            "（《机动车驾驶证申领和使用规定》第七十二条第三款）。\n"
            "2. **其他准驾车型**（C 类、摩托车等）驾驶人——发生交通事故**造成人员死亡、"
            "承担同等以上责任且未被吊销驾驶证**的（第七十二条第四款）。\n"
            "3. **校车驾驶人**——**每个记分周期都要审，没有\"无记分免审\"的优待**（第九十条）。\n"
            "4. **70 周岁以上**驾驶人——发生责任交通事故造成人员**重伤或者死亡**的，"
            "审验时还要加做记忆力、判断力、反应力测试（第七十二条第五款、第七十三条第三款）。\n\n"
            "**审验内容**（第七十三条）：违法和事故处理情况、身体条件、记分及满分学习考试情况。"
            "有违法或事故未处理完毕、身体条件不合格、未按规定参加学习考试的，**不予通过审验**。\n\n"
            "**在哪审**：核发地或核发地以外的任何地方都可以（第七十二条第六款）。",
            [source(f"{LAW}第七十二条、第七十三条、第九十条",
                    "持有大型客车、重型牵引挂车、城市公交车、中型客车、大型货车驾驶证的驾驶人，"
                    "应当在每个记分周期结束后30日内到公安机关交通管理部门接受审验。"
                    "但在1个记分周期内没有记分记录的，免予本记分周期审验。"
                    "持有第三款规定以外准驾车型驾驶证的驾驶人，发生交通事故造成人员死亡承担同等以上责任"
                    "未被吊销机动车驾驶证的，应当在本记分周期结束后30日内……接受审验。",
                    "driving_license.md")],
            "REVIEW:LIST")

    if re.search(r"(校车)", q):
        return result(
            "**校车驾驶人：每个记分周期结束后 30 日内接受审验，每年都要审。**\n\n"
            "依据第九十条：审验时应当提交医疗机构出具的有关身体条件的证明，"
            "参加不少于 **3 小时**的道路交通安全法律法规、交通安全文明驾驶、应急处置等知识学习，"
            "并接受交通事故案例警示教育。\n\n"
            "⚠️ 与普通驾驶人不同：校车驾驶人**没有\"无记分免审\"的优待**，每个记分周期都要审验。",
            [source(f"{LAW}第九十条",
                    "校车驾驶人应当在每个记分周期结束后30日内到公安机关交通管理部门接受审验")],
            "REVIEW:SCHOOLBUS")

    # 学时/内容型问句。这里只留"问多久、问学什么"的信号词，不再用 (学习|教育)
    # 这种业务名词本身做信号——业务名词几乎出现在所有审验问题里，等于没有闸门。
    if re.search(r"(学多久|多少小时|几小时|多长时间|学时|学习什么|学什么|学习内容|学几天)", q):
        return result(
            "**审验教育不少于 3 小时。**\n\n"
            "依据第七十三条第三款：持 A1、A2、A3、B1、B2 驾驶证，"
            "一个记分周期内有记分的，以及持其他准驾车型驾驶证发生交通事故造成人员死亡"
            "承担同等以上责任未被吊销驾驶证的驾驶人，审验时应当参加**不少于 3 小时**的"
            "道路交通安全法律法规、交通安全文明驾驶、应急处置等知识学习，并接受交通事故案例警示教育。\n\n"
            "⚠️ 注意区分\"满分教育\"：记满 12 分参加的是满分学习，"
            "一般驾驶人 **7 天**、AB 类驾驶人 **30 天**（163号令第十八条），与审验教育不是一回事。",
            [source(f"{LAW}第七十三条第三款",
                    "审验时应当参加不少于3小时的道路交通安全法律法规、交通安全文明驾驶、应急处置等知识学习")],
            "REVIEW:EDU")

    codes = extract_codes(q)
    if re.search(r"(A、B|AB类|A类|B类|大车)", q) or (codes and codes[0] in ("A1", "A2", "A3", "B1", "B2")):
        return result(
            "**A、B 类驾驶证（A1/A2/A3/B1/B2）：每个记分周期结束后 30 日内接受审验；"
            "1 个记分周期内没有记分记录的，免予本记分周期审验。**\n\n"
            "依据第七十二条第三款。\n\n"
            "**其他准驾车型**（C1/C2 等）平时不需要每年审验，只有两种情形需要：\n"
            "1. 发生交通事故造成人员死亡、承担同等以上责任且未被吊销驾驶证的，"
            "应当在本记分周期结束后 30 日内接受审验（第七十二条第四款）；\n"
            "2. 70 周岁以上驾驶人发生责任交通事故造成人员重伤或者死亡的，"
            "应当在本记分周期结束后 30 日内接受审验（第七十二条第五款）。\n\n"
            "审验内容（第七十三条）：违法与事故处理情况、身体条件情况、记分及满分学习考试情况。"
            "有记分的 AB 类驾驶人审验时须参加不少于 **3 小时**学习；"
            "70 周岁以上驾驶人审验时须进行记忆力、判断力、反应力等能力测试。",
            [source(f"{LAW}第七十二条第三款",
                    "持有大型客车、重型牵引挂车、城市公交车、中型客车、大型货车驾驶证的驾驶人，"
                    "应当在每个记分周期结束后30日内到公安机关交通管理部门接受审验。"
                    "但在1个记分周期内没有记分记录的，免予本记分周期审验")],
            "REVIEW:AB")
    return None


