def q_limb(q: str) -> Optional[Dict]:
    if not re.search(r"(上肢|下肢|手指|手掌|肢体|截肢|残疾|缺失|断肢|手臂|胳膊|腿)", q):
        return None
    if re.search(r"(视力|眼睛|色盲|色弱|听力|身高)", q):
        return None

    if "拇指" in q:
        if re.search(r"左", q):
            return result(
                "**左手拇指缺失，可以申请 C1、C2、C3、C4 四种准驾车型。**\n\n"
                "依据第十四条第二项第5目：上肢要求「双手拇指健全，每只手其他手指必须有三指健全」，"
                "但**手指末节残缺或者左手有三指健全、且双手手掌完整的**，"
                "可以申请小型汽车（C1）、小型自动挡汽车（C2）、低速载货汽车（C3）、三轮汽车（C4）。\n\n"
                "⚠️ 三个要点：\n"
                "1. 放宽只针对**左手**——右手拇指缺失不在放宽范围内，不能申请；\n"
                "2. 还要求**双手手掌完整**、左手其他手指有三指健全、肢体和手指运动功能正常；\n"
                "3. 想开 C5（残疾人专用小型自动挡载客汽车）另需符合第 8 目条件。\n\n"
                "最终以指定体检机构的检查结论为准。",
                [source(f"{LAW}第十四条第二项第5目",
                        "手指末节残缺或者左手有三指健全，且双手手掌完整的，可以申请小型汽车、小型自动挡汽车、"
                        "低速载货汽车、三轮汽车准驾车型的机动车驾驶证")],
                "PHYSICAL:thumb_left")
        return result(
            "**关键看是哪只手的拇指缺失：**\n\n"
            "- **左手拇指缺失**：属于第 5 目的放宽情形（左手有三指健全且双手手掌完整），"
            "可以申请 **C1、C2、C3、C4** 四种准驾车型；\n"
            "- **右手拇指缺失**：第 5 目要求「双手拇指健全」，放宽条款只针对「手指末节残缺」或「左手」，"
            "右手拇指缺失**不符合**上肢条件，不能申请。\n\n"
            "依据：第十四条第二项第5目。具体以指定体检机构的检查结论为准。",
            [source(f"{LAW}第十四条第二项第5目",
                    "上肢：双手拇指健全，每只手其他手指必须有三指健全，肢体和手指运动功能正常。"
                    "但手指末节残缺或者左手有三指健全，且双手手掌完整的，可以申请小型汽车、小型自动挡汽车、"
                    "低速载货汽车、三轮汽车准驾车型的机动车驾驶证")],
            "PHYSICAL:thumb")

    for pat, cond, codes, item in LIMB_RULES:
        if not re.search(pat, q):
            continue
        if codes:
            body = (f"**{cond}，可以申请：{_fmt(codes)}。**\n\n"
                    f"依据：第十四条第二项{item}。\n\n")
            if "C5" in codes:
                body += ("⚠️ 这是**残疾人专用小型自动挡载客汽车（C5）**，不是 C1/C2。\n"
                         "C5 只能驾驶残疾人专用小型、微型自动挡载客汽车，"
                         "不能驾驶普通小型汽车。\n\n")
            body += ("补充：残疾人专用小型自动挡载客汽车还需在车身设置残疾人机动车专用标志（附件4），"
                     "并按第七十六条规定，70 周岁以上不得驾驶 C6、C3、C4、D、E 等车型。")
            return result(body, [source(f"{LAW}第十四条第二项{item}", cond)], "PHYSICAL:limb")
        return result(
            f"**{cond}，不符合第十四条第二项第 5 目的上肢条件，不能申请机动车驾驶证。**\n\n"
            "第 5 目要求：双手拇指健全，每只手其他手指必须有三指健全，肢体和手指运动功能正常。"
            "只有「手指末节残缺」或「左手有三指健全且双手手掌完整」的，"
            "才放宽到 C1、C2、C3、C4。\n\n"
            "具体是否符合，以指定体检机构的检查结论为准。",
            [source(f"{LAW}第十四条第二项第5目",
                    "上肢：双手拇指健全，每只手其他手指必须有三指健全，肢体和手指运动功能正常")],
            "PHYSICAL:limb_no")
    return None


def _fmt(codes: List[str]) -> str:
    return "、".join(f"{c}（{LICENSE_TABLE[c]['name']}）" for c in codes if c in LICENSE_TABLE)


