def q_no_ab(q: str) -> Optional[Dict]:
    """禁申（"还能不能考/申请/增驾"）—— 第十五条（全车型）+ 第十八条（仅 AB 类）。

    设计要点：不再用一串 if 逐个关键词判断，而是把两部条文的每一款做成表项
    （正则 → 条款原文 → 禁止范围 → 期限），命中几项就报几项。

    为什么必须分"全部车型"和"AB 类"两层？
    同一个事实（如吸毒记录）在第十五条里禁全部车型、在第十八条里只禁 AB 类；
    如果不分层，就会出现"有社区戒毒记录"一律被答成"不得申请 AB 类"，
    而用户问的是 A3 —— 结论对了一半，另一半（连 C1 都考不了）丢了。
    """
    qn = norm(q)

    # 动作守卫：问的是"能不能申请/考/增驾/重新取得"，而不是"多久能重考""怎么恢复"
    if not re.search(r"(能考|可以考|能不能考|还能考|能申请|可以申请|能增驾|可以增驾|"
                     r"能拿|可以拿|能领|能重新|不得申请|不能申请|不允许申请|禁止申请|"
                     r"还能申请|是否可以申请|可不可以)", qn):
        return None
    if re.search(r"(多久|几年|多长时间|什么时候|何时)", qn):
        # 问期限的交给 REVOKE（吊销后几年可重考），本条只管"能不能"
        return None

    codes = extract_codes(qn)
    ab = bool(re.search(AB_WORDS, qn)) or any(c in AB_CODES for c in codes)

    hits = [it for it in BAN_TABLE if re.search(it["pat"], qn)]

    # 单次饮酒 ≠ 醉酒/再次饮酒：第十八条未列入禁止情形，不能一概说"不能"
    if not hits and re.search(r"(酒驾|饮酒|喝酒|酒后)", qn):
        return result(
            "**要看你属于哪一种「酒驾记录」，结论不同：**\n\n"
            "- **醉酒后驾驶机动车** → **不得申请** A1/A2/A3/B1/B2（第十八条第二项）；\n"
            "- **再次饮酒后驾驶机动车**（第二次及以后）→ **不得申请** A1/A2/A3/B1/B2（第十八条第三项）；\n"
            "- **单次饮酒后驾驶**（未达醉酒）→ 第十八条未将其列入禁止情形，"
            "**法律上不当然禁止**申请 B2；但该次违法一次记 **12 分**，"
            "而增驾要求「本记分周期和申请前最近 1 个记分周期内没有记满 12 分记录」（第十七条），"
            "所以在记分未清除前**实际上无法通过审核**；\n"
            "- 若已因酒驾被**吊销**驾驶证 → 在禁申期限内（饮酒驾驶营运车 5 年、醉酒 5 年、"
            "醉酒驾驶营运车 10 年）不得申请任何准驾车型。\n\n"
            "⚠️ 各地对「酒驾记录」的审核口径可能更严，建议报名前先到车管所核查本人驾驶档案。",
            [source(f"{LAW}第十八条第二项、第三项、第十七条",
                    "醉酒后驾驶机动车的；再次饮酒后驾驶机动车的——不得申请大型客车、重型牵引挂车、"
                    "城市公交车、中型客车、大型货车准驾车型")],
            "NO_AB:DRINK")

    if not hits:
        return None

    # 只命中 AB 类条款、而问题里没有 AB 车型 → 与提问不符，让位
    if not ab and all(it["scope"] == "ab" for it in hits):
        return None

    lines = []
    for it in hits:
        scope_txt = "**所有准驾车型**" if it["scope"] == "all" else "**A1/A2/A3/B1/B2（大中型客货车）**"
        lines.append(f"- **{it['item']}** → 不得申请 {scope_txt}，期限：**{it['dur']}**（{it['ref']}）")

    all_scope = [it for it in hits if it["scope"] == "all"]
    ab_scope = [it for it in hits if it["scope"] == "ab"]

    head = "**不能。**\n\n" if hits else ""
    body = "你描述的情形对应以下禁止申领条款：\n" + "\n".join(lines)

    tail = ""
    if all_scope and ab_scope:
        tail = ("\n\n⚠️ 注意两层区别：**第十五条**列的是「不得申请机动车驾驶证」，"
                "**连 C1、摩托车都不能考**；**第十八条**只限制 A1/A2/A3/B1/B2，"
                "C1、C2、C5、C6、D、E、F 等仍可正常申请。你同时触及两层，"
                "按更严的那一层执行。")
    elif ab_scope:
        tail = ("\n\n⚠️ 注意：**这不等于终身不能考驾照。**第十八条限制的只是 AB 类"
                "（A1/A2/A3/B1/B2），C1、C2、C3、C4、C5、C6、D、E、F 等小型汽车和摩托车准驾车型"
                "仍可正常申请（法律另有规定的除外）。")
    elif all_scope:
        tail = "\n\n⚠️ 上述情形禁止的是**全部准驾车型**，不是只禁 AB 类。"

    return result(
        head + body + tail,
        [source(f"{LAW}第十五条、第十八条",
                "有下列情形之一的，不得申请机动车驾驶证……；有下列情形之一的，"
                "不得申请大型客车、重型牵引挂车、城市公交车、中型客车、大型货车准驾车型……")],
        "BAN:" + (hits[0]["key"] if len(hits) == 1 else "MULTI"))


