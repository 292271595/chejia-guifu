    (r"(右下肢).{0,6}(缺失|截肢|丧失)",
     "右下肢缺失或者丧失运动功能，但能够自主坐立且上肢符合第 5 目规定的",
     ["C5"], "第8目"),
    (r"(左下肢).{0,6}(缺失|截肢|丧失)",
     "单独左下肢缺失或者丧失运动功能，但右下肢正常的",
     ["C2"], "第6目"),
