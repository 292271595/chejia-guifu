# 三、换证 / 有效期 / 核发地变更
# ============================================================
def q_renew(q: str) -> Optional[Dict]:
    if not re.search(r"(换证|换领|有效期|到期|过期|超期|失效|核发地|转入|迁入|异地|延期)", q):
        return None

    # 有效期是几年（第十三条）
    if re.search(r"有效期", q) and re.search(r"(几年|多少年|多长|多久)", q) \
            and not re.search(r"(学习驾驶|临时|10\s*年|十年)", q):
        return result(
            "**机动车驾驶证有效期分为 6 年、10 年和长期三档（第十三条）。**\n\n"
            "初次申领的驾驶证有效期是 **6 年**；之后按记分情况升级：\n"
            "- 6 年有效期内**每个记分周期均未记满 12 分** → 换发 **10 年**有效期驾驶证；\n"
            "- 10 年有效期内**每个记分周期均未记满 12 分** → 换发**长期**有效驾驶证（第六十二条）。\n\n"
            "⚠️ 只要有一个记分周期记满 12 分，就不能升级，仍按原有效期档次换发。",
            [source(f"{LAW}第十三条、第六十二条",
                    "机动车驾驶证有效期分为6年、10年和长期；机动车驾驶人在机动车驾驶证的6年有效期内，"
                    "每个记分周期均未记满12分的，换发10年有效期的机动车驾驶证")],
            "RENEW:VALIDITY")

