# 五、口语规范化 / 关键词工具
# ============================================================
def norm(question: str) -> str:
    """口语规范化：把常见口语说法换成法规用语，便于匹配。

    注意顺序与边界：先把"醉驾"归一为"醉酒"，再用否定环视处理剩余"酒驾"，
    否则 "醉酒" 中的 "酒驾" 会被二次替换成 "醉饮酒"，污染关键词。
    """
    q = question.replace("醉驾", "醉酒")
    # 「喝醉／喝醉了」也是明确的醉酒口语，不等于泛称「喝了酒」。
    # 统一放在饮酒归一之前，避免营运车十年禁申掉回原因不明的总表。
    q = re.sub(r"喝醉了?", "醉酒", q)
    q = re.sub(r"(?<!醉)酒驾", "饮酒", q)
    # 「喝了点酒」「喝了酒」「喝酒」「酒后」都是饮酒驾驶的口语说法。
    # 不归一的话，"我朋友喝了点酒开车被查了"整句不含任何违法术语，
    # 会被判成非违法问句、掉进 RAG 后答"暂无信息"——而这是最高频的一类真实问法。
    # 「酒后」必须加否定环视：上面刚把"醉驾"换成"醉酒"，得到"醉酒后…"，
    # 这串里含子串"酒后"，不带 (?<!醉) 就会被替换成"醉饮酒后"，
    # 于是整句多出一个"饮酒"，被"先分清饮酒还是醉酒"那支并陈模板吃掉——
    # 用户明明说了醉驾，却拿不到"5 年"这个确切答案。（实测 4 条抢答回归因此挂红）
    q = re.sub(r"(?:喝了?点?酒|喝了酒|喝酒|(?<!醉)酒后)", "饮酒", q)
    q = q.replace("扣分", "记分").replace("驾照", "驾驶证")
    # 「本子」「本儿」是驾驶证的口语叫法（"本子过期了还能用不"）
    q = q.replace("本子", "驾驶证").replace("本儿", "驾驶证")
    # 「啥」「咋」是最高频的两个口语疑问词，但事实层的主题正则基本只写了
    # 「什么」「怎么」。逐个处理器去补「|啥」是治不完的，在入口统一归一一处解决。
    # 实测（tools/expand_questions.py）：不改这里，「什么→啥」这一档变体只有
    # 82.8% 能命中，改完补齐。注意 "为啥" 会一并变成 "为什么"，正好也是规范说法。
    q = q.replace("啥", "什么").replace("咋", "怎么")
    return q


def has(text: str, words) -> bool:
    return any(w in text for w in words)


