# ============================================================
# 八、核载人数与准驾车型（9 座 / 中型客车 / 大型客车）
# ============================================================
def q_seat(q: str) -> Optional[Dict]:
    m = re.search(r"(\d+)\s*座", q)
    if not m:
        return None
    n = int(m.group(1))
    codes = extract_codes(q)
    holder = codes[0] if codes else None

    if n <= 9:
        need = "C1（小型汽车）"
        detail = ("按《道路交通管理 机动车类型》（GA 802—2019），**车长小于 6 米且核定载客人数"
                  "不超过 9 人**的载客汽车属于**小型载客汽车**，C1 准予驾驶。"
                  f"所以 {n} 座客车（含 {n} 座面包车）持 **C1** 就可以开。")
        ok = holder in (None, "C1", "C2", "C3", "C4", "B1", "B2", "A1", "A2", "A3")
    elif n <= 19:
        need = "B1（中型客车）"
        detail = (f"{n} 座属于**中型载客汽车**（核载 10 人以上、19 人以下），"
                  "需要 **B1（中型客车）** 或 A1 驾驶证。C1 不能驾驶。")
        ok = holder in (None, "B1", "A1", "A2")
    else:
        need = "A1（大型客车）"
        detail = (f"{n} 座属于**大型载客汽车**（核载 20 人以上），需要 **A1（大型客车）** 驾驶证。"
                  "B1、C1 均不能驾驶。")
        ok = holder in (None, "A1")

    if holder:
        head = (f"**{'能。' if ok else '不能。'}** 持 {holder}（{LICENSE_TABLE[holder]['name']}）"
                f"{'可以' if ok else '不能'}驾驶 {n} 座客车。\n\n")
    else:
        head = f"**{n} 座客车需要 {need} 驾驶证。**\n\n"
    return result(head + detail,
                  [source("《道路交通管理 机动车类型》（GA 802—2019）、"
                          "《机动车驾驶证申领和使用规定》附件1",
                          "小型载客汽车：车长小于6米且核定载客人数小于等于9人的载客汽车；"
                          "中型载客汽车：车长小于6米且核定载客人数大于9人小于20人的载客汽车", SRC_INSPECT)],
                  "VEHICLE:SEAT")


