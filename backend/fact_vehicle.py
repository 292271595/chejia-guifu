def q_vehicle(question: str) -> Optional[Dict]:
    for fn in (q_seat, q_vehicle_category, q_transfer, q_scrap, q_overdue_inspection,
               q_cross_region_inspect, q_online_year, q_exemption, q_inspection_cycle):
        try:
            r = fn(question)
        except Exception as e:
            print(f"[fact_vehicle] {fn.__name__} 异常: {e}")
            r = None
        if r:
            return r
    return None
