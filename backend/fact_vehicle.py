# ------------------------------------------------------------
# 取消免检资格的两种情形（公交管〔2022〕295号第四条）
# ------------------------------------------------------------
# 条文原话：「车辆发生造成人员伤亡的交通事故或者非法改装被依法处罚的，
# 仍按原规定周期检验。」这条是优化周期的**例外**，而旧实现在检验周期分支里
# 完全没有它——问「发生伤人事故后检车周期有变化吗」，答的是标准优化周期
# （10 年内每 2 年、第 6/10 年上线），正好答反：该车恰恰不能这么检。
#
# 两个必须处理的边界：
#   1. 要件是「造成人员伤亡」。仅财产损失（剐蹭、追尾没人受伤）不触发，
#      否则一句「就蹭掉点漆没人受伤，年检变吗」会被答成要恢复原周期。
#   2. 「事故车」单独出现时不能直接判定，只能分情况讲——用户的车可能只是被追尾。
_CASUALTY = re.compile(
    r"(人员伤亡|伤亡事故|伤人事故|致人伤亡|人员受伤|有人受伤|有人死亡|致人死亡|"
    r"撞伤|撞死|撞伤人|撞了人|撞过人|伤了人|伤者|致人受伤)"
)
_NEG_CASUALTY = re.compile(
    r"(没有|没|未|无|不曾|并非|不是|不算|不属于)[^，。？?]{0,8}"
    r"(人员伤亡|伤亡|伤人|人员受伤|受伤|撞伤|撞死)"
)
_MOD_PENALTY = re.compile(
    r"(非法改装|私自改装|擅自改装|改装|改型)[^，。？?]{0,14}"
    r"(被处罚|被罚|处罚过|被查处|被查过|被查|查到|被罚款|已被处罚|被处理)"
)


def _lost_exemption(q: str) -> bool:
    """是否落入「取消免检资格」的两类法定情形（伤亡事故 / 非法改装被处罚）。"""
    if _MOD_PENALTY.search(q):
        return True
    if _NEG_CASUALTY.search(q):
        return False
    return bool(_CASUALTY.search(q))


# 只提了「事故」但没说伤没伤人。这种不能替用户假定，也不能装没看见——
# 「出了事故以后多久检一次车」如果只答标准周期，恰好是那个错误答案。
_ACCIDENT_ANY = re.compile(r"(事故|撞了|撞过|被撞|追尾|剐蹭)")
_NEG_ACCIDENT = re.compile(r"(没有|没出|没发生|没遇到|无|未曾|不曾)[^，。？?]{0,4}(事故|撞)")


def _accident_touched(q: str) -> bool:
    """是否提到事故（但未明确是否造成人员伤亡）。"""
    if _NEG_ACCIDENT.search(q):
        return False
    return bool(_ACCIDENT_ANY.search(q))

