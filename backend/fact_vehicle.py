        "**三个条件要同时满足**：\n"
        "1. 车型必须是**小型、微型载客汽车**（家用轿车、SUV）；货车、大中型客车、摩托车不适用这一项；\n"
        "2. **不改变车身主体结构**（打孔加固、切割、焊接车顶都不行）；\n"
